"""handoff.md: one Markdown file to hand a repository over to Claude Code (or a person).

It holds the flows (numbered chains, entry point to sink), the overview (every line with
its ``file:line``), the three diagrams as Mermaid
blocks, and, when a previous run exists, what changed since. Built from model.json and
the repository files only: deterministic, offline, no LLM.
"""

from __future__ import annotations

from typing import Any

from . import __version__
from .flow import build_flows, render_flows_markdown
from .output import listing_text
from .overview import build_overview, render_overview_markdown
from .snapshots import changes_markdown
from .snippets import SourceLines
from .visuals import DIAGRAMS, TITLES, mermaid


def render_handoff(
    model: dict[str, Any],
    title: str,
    source: SourceLines | None = None,
    changes: dict[str, Any] | None = None,
    commit: str = "",
) -> str:
    git = (model.get("crawl") or {}).get("git") or {}
    commit = commit or git.get("head", "")
    discovery = model.get("discovery") or {}
    listing = listing_text(discovery["inventory"]) if discovery.get("inventory") else ""
    out = [
        f"# TFLens handoff: {title}",
        "",
        f"Generated by TFLens {__version__} from a static, read-only, offline analysis of "
        + (f"commit `{commit[:12]}`" if commit else "the working tree")
        + " (no terraform run, no cloud calls, no LLM). "
        "Every statement below ends with the `file:line` it was read from; values that "
        "cannot be known statically are marked UNKNOWN with the reason.",
        "",
        "## How to use this file with Claude Code",
        "",
        "- Open Claude Code at the root of the repository and give it this file as context "
        "(for example `@handoff.md`), then ask your question.",
        "- Treat the `file:line` references as the source of truth: open them before "
        "changing code; the overview and diagrams are derived from them.",
        "- Purpose lines marked *Guess* are heuristics from the README and resource "
        "counts, not facts.",
        "- The diagrams are Mermaid: they render on GitHub / GitLab or with `mmdc`.",
        "- Flow steps marked *unverified* have a reference but no IAM grant; *can write* / "
        "*can read* have an IAM grant but no reference.",
        "",
        render_flows_markdown(build_flows(model), level=2).rstrip(),
        "",
        render_overview_markdown(build_overview(model, title, source), listing, level=2).rstrip(),
        "",
        "## Diagrams",
        "",
    ]
    for name in DIAGRAMS:
        out += [f"### {TITLES[name]}", "", "```mermaid", mermaid(model, name).rstrip(), "```", ""]
    if changes is not None:
        out += [changes_markdown(changes, "Changes since the previous run").rstrip(), ""]
    return "\n".join(out).rstrip() + "\n"
